// Regenerates `lib/games/board_index.g.dart` from every
// `lib/games/<pkg>/boards.dart`.
//
// Each game package's board UI is imported as a *deferred* library so the web
// build splits it out of main.dart.js and only downloads it when that game is
// actually opened. Run this after adding a new game package or a new game id:
//
//   cd webclient
//   dart run tool/gen_boards.dart
//
// test/board_index_test.dart verifies the generated index against the real
// package maps, so a stale index fails CI.
import 'dart:io';

void main() {
  final root = Directory('lib/games');
  if (!root.existsSync()) {
    stderr.writeln('Run from the webclient directory.');
    exit(2);
  }
  final pkgs = [
    for (final d in root.listSync().whereType<Directory>())
      if (File('${d.path}/boards.dart').existsSync()) d.uri.pathSegments.where((s) => s.isNotEmpty).last,
  ]..sort();

  final mapDecl = RegExp(r'Map<String,\s*BoardBuilder>\s+(\w+)\s*=\s*(?:const\s*)?\{([\s\S]*?)\n\};');
  // Map keys (`'id': ...`) and ids listed in a `for (final id in const [...])` comprehension.
  final idLit = RegExp(r"^\s*'([a-z0-9_]+)'\s*[:,\]]", multiLine: true);

  final owner = <String, String>{};
  final mapNames = <String, String>{};
  var failed = false;
  for (final p in pkgs) {
    final src = File('lib/games/$p/boards.dart').readAsStringSync();
    final m = mapDecl.firstMatch(src);
    if (m == null) {
      stderr.writeln('lib/games/$p/boards.dart: no `final Map<String, BoardBuilder> xxxBoards = {...};` found');
      failed = true;
      continue;
    }
    mapNames[p] = m.group(1)!;
    final ids = idLit.allMatches(m.group(2)!).map((x) => x.group(1)!).toSet();
    if (ids.isEmpty) {
      stderr.writeln('lib/games/$p/boards.dart: no game ids found in ${m.group(1)}');
      failed = true;
    }
    for (final id in ids) {
      final prev = owner[id];
      if (prev != null) {
        stderr.writeln('duplicate board id "$id" in packages $prev and $p');
        failed = true;
      }
      owner[id] = p;
    }
  }
  if (failed) exit(1);

  final index = {for (var i = 0; i < pkgs.length; i++) pkgs[i]: i};
  final b = StringBuffer()
    ..writeln('// GENERATED by `dart run tool/gen_boards.dart` - do not edit by hand.')
    ..writeln('// Every package is a deferred library: the web build emits one')
    ..writeln('// main.dart.js_N.part.js per package, downloaded on first use.')
    ..writeln('// ignore_for_file: library_prefixes')
    ..writeln()
    ..writeln("import 'board_package.dart';");
  for (final p in pkgs) {
    b.writeln("import '$p/boards.dart' deferred as b_$p;");
  }
  b
    ..writeln()
    ..writeln('/// All board packages, sorted by directory name.')
    ..writeln('final List<BoardPackage> boardPackages = [');
  for (final p in pkgs) {
    b.writeln("  BoardPackage('$p', () => b_$p.loadLibrary(), () => b_$p.${mapNames[p]}),");
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// Game id -> index into [boardPackages].')
    ..writeln('const Map<String, int> boardPackageOf = {');
  final ids = owner.keys.toList()..sort();
  for (final id in ids) {
    b.writeln("  '$id': ${index[owner[id]]},");
  }
  b.writeln('};');

  File('lib/games/board_index.g.dart').writeAsStringSync(b.toString());
  stdout.writeln('board_index.g.dart: ${pkgs.length} packages, ${ids.length} games');
}
