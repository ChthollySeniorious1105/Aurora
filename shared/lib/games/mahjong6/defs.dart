const _shaanxiRules = '''
# 陕西麻将（下炮子 · 红中固定赖子 · 四红中暴击）
4 人对局，使用万、筒、条（1~9 共 108 张）外加 4 张红中（7z），全副共 112 张牌。不可吃牌，可碰、杠、点炮或自摸胡牌。
# 第一阶段：下炮子（0~4 炮）
- 每局发牌后进入【下炮子（paozi）】阶段，每位玩家自由选择本局押注的炮子数（0 子 ~ 4 子）。
- 胡牌结算时，赢家与每一位付款输家之间的赔付分数额外加上【赢家炮子数 + 输家炮子数】（+(paozi[winner] + paozi[loser])）！
# 红中固定赖子（7z）与四红中
- 红中（7z）在手牌中固定作为万能百搭赖子，可代替任意牌组成顺子、刻子、将牌或七对；无红中代牌成胡可获得【硬胡】加番。
- 四红中：轮到自己行动时，若手中集齐全部 4 张红中（7z），无论其余手牌是否成面子，均可立即发动【四红中】直接自摸胡牌并翻倍结算！
- 杠牌即时结算：暗杠三家各赔 2 分，明杠点杠者赔 2 分，补杠三家各赔 1 分。支持【可点炮可自摸】与【只炸不胡（只许自摸）】两种模式。
''';

const _hefeiRules = '''
# 合肥麻将（84 张断幺牌池 · 缺一门 · 够八支 · 十同 / 双八支）
4 人对局，采用安徽合肥独具特色的【84 张断幺无字牌池】：剔除全部幺九牌（1、9）与全部字牌（东南西北白发中），仅保留万、筒、条的 2~8 共 21 种 × 4 张 = 84 张牌！不可吃牌，支持碰、杠、自摸与点炮胡牌。
# 合肥麻将铁律：缺一门 + 够八支
任何 4 面子 + 1 将牌或七对手牌，必须同时满足以下两大硬性条件才允许胡牌：
- 缺一门：手牌与副露合计最多只能包含万（m）、筒（p）、条（s）中的 2 门花色（至少缺一门）。
- 够八支：主花色（张数最多的一门花色，含碰/杠副露）的牌张数必须达到【至少 8 张（>= 8 支）】！
# 特色番型：十同、双八支、清一色与七对
- 够八支（2 番）：满足主花色 >= 8 张的基础胡牌。
- 十同（4 番，×2）：主花色牌张数达到 10 张及以上（>= 10 支）。
- 双八支（6 番，×2）：在拥有杠牌（四张计 4 支）的情况下，两门花色同时达到各 8 张及以上（8 支 + 8 支）！
- 清一色（8 番，×4）：全副手牌与副露全部由同一门花色组成（>= 14 支）。
- 七对（4 番，×2）与对对胡（2 番）：可与够八支、十同、清一色叠加计分！
''';

