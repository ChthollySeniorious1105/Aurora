const math24Rules = '''
# 概述
- 1~8 人同时抢答的心算派对游戏（算术 24 点）。
- 每一题系统发出 4 张数字牌（严格保证至少存在一种加减乘除算出 24 的解法）。
- 所有玩家在各自独立的工作区中同时作答，通过两两合并数字最终得出 24。

# 操作与分步计算
- 分步合并：在你的工作区中依次点击第一个数、运算符（`+`、`-`、`×`、`÷`）、第二个数，即可将这两个数合并为一个新结果（4 个数 → 3 个数 → 2 个数 → 1 个数）。
- 分数支持：除法运算支持精确分数（例如 `5 ÷ 2 = 5/2`），不会产生浮点数舍入误差；除数不能为 0。
- 撤销与重置：如果算错或走入死胡同，随时可以点击「撤销」退回上一步，或点击「重置」恢复本轮初始的 4 个数字。
- 跳过本轮：如果实在想不出解法，可以点击「跳过」放弃本题，等待下一题。

# 计分与流程
- 每道题中，第 1 位算出 24 的玩家获得 **10 分**（速度奖励），第 2 位算出 24 的玩家获得 **8 分**，第 3 位及之后算出 24 的玩家获得 **6 分**。
- 选择「跳过」或超时未算出的玩家本题得 0 分。
- 当所有在场玩家都已完成（算出 24 或跳过）或本题倒计时结束时，展示本题参考解法，随后自动进入下一题。
- 全部题目完成后，按总积分从高到低排名；积分相同时按解出题数、累计用时排名。

# 选项
- 题数：5 题 / 10 题。
- 数字范围：1~10 简单 / 1~13 标准（含 J=11、Q=12、K=13）。

# 电脑玩家
- 简单电脑思考较慢，偶尔会走弯路或跳过难题；普通与困难电脑会快速心算并分步合并出 24。
''';

const tankBattleRules = '''
# 概述
- 2~4 人在 15×15 网格战场上展开的经典坦克大战。四名玩家分别从战场四角出生。
- 战场上分布着可摧毁的砖墙、坚固的钢铁墙、提供隐蔽的草丛、以及阻挡履带但炮弹可飞越的水域。
- 目标：驾驶坦克走位、射击、收集空投道具，击毁所有敌方坦克，成为最后幸存的王牌车长！

# 地形说明
- 🧱 砖墙：阻挡坦克与炮弹，被任意炮弹命中即被摧毁，并有一定几率掉落强化道具。
- 🔩 钢铁墙：普通炮弹无法击穿；拾取 2 颗星级强化后的重型穿甲弹可摧毁内部钢铁墙（外围边界护墙不可摧毁）。
- 🌿 草丛：坦克与炮弹均可自由穿过，驶入草丛可获得视觉隐蔽效果。
- 🌊 水域：坦克无法驶入水面，但炮弹可以毫无阻碍地飞越水域。

# 操作与战斗
- 移动：方向键 / WASD 或屏幕十字方向键控制坦克转向与前进。
- 开火：空格键 / 回车 / J 键或屏幕「开火」按钮发射炮弹。
- 生命与重生：每次被敌方炮弹命中（且无护盾保护）扣除 1 点生命值；若仍有剩余生命，坦克会在安全的出生点重生并获得短暂出生护盾；生命归零则淘汰出局。

# 战场道具
- 🛡️ 护盾（S）：立即获得一段时间的能量护盾，可抵挡炮弹伤害。
- ⚡ 速射（F）：装填速度加快，且允许同时在场多枚炮弹。
- ⭐ 强化（U）：提升坦克星级（1 星提升机动与射速；2 星升级为可击穿内部钢铁墙的重型穿甲弹）。
- 🔧 维修（H）：恢复 1 点生命值并获得额外积分。

# 胜负与排名
- 当战场只剩 1 辆或 0 辆坦克存活时对局立即结束；若时间耗尽，则存活坦克排在前面，按剩余生命、击杀数与战斗积分排名。

# 选项
- 生命数：3 命 / 5 命。
- 战场地图：标准战场（均衡巷战）/ 钢铁迷宫（掩体走廊）/ 丛林水网（河道与草丛伏击）。
''';

const mjConnectRules = '''
# 概述
- 1~6 人同场竞速的麻将连连看派对游戏（连连看竞速）。
- 所有玩家开局获得完全相同的麻将图案网格，各自在自己的棋盘上寻找并消除配对。

# 消除规则
- 点击两张图案相同的牌，若它们之间可以用 **不超过 3 条直线段（即最多转弯 2 次）** 连接，且路径经过的格子全部为空格（允许经过棋盘外围一圈的虚拟边界通道），即可将这对牌消除！
- 每次成功消除一对牌得 **10 分**，棋盘上会短暂高亮显示连通折线。

# 自动洗牌与手动洗牌
- 自动洗牌：当你的棋盘上还有剩余牌，但没有任何一对牌可以在两次转弯内连通时，系统会自动将剩余牌重新洗牌，确保始终有解。
- 手动洗牌：如果你一时找不到可消除的配对，可以点击「洗牌」按钮主动重排剩余牌（每局最多可主动使用 3 次，每次扣除 2 分）。

# 胜负与排名
- 最先将自己棋盘上所有牌全部消除的玩家立即获胜！
- 若规定时间内无人清空或单人挑战结束，则按已消除对数、积分及完成时间从高到低排名。
- 认输的玩家排在所有未认输玩家之后。

# 选项
- 棋盘大小：小型 6×4（12 对）/ 标准 6×6（18 对）/ 大型 8×6（24 对）。

# 电脑玩家
- 电脑玩家会实时扫描自己棋盘上的可连配对：简单电脑消除较慢，困难电脑眼疾手快。
''';
