const String ricochetRules = '''
# 弹射机器人（Ricochet Robots）

# 游戏概述
- 支持 1～8 人同时游玩的空间路径规划竞速派对游戏。
- 棋盘为 10×10（标准）或 12×12（扩展）网格，四周设有外墙，内部散布 L 形折角墙壁与边墙凸起，场上有红、绿、蓝、黄 4 台彩色机器人。
- 每局揭示一个目标终点（指定颜色的机器人与目标格子），系统通过广度优先搜索（BFS）严格保证该目标在当前局面下 2～6 步滑行内必有最短解。

# 滑行规则
- 任意一台机器人都可以向「上、右、下、左」四个方向发射滑行。
- 机器人一旦开始滑行，必须沿着直线一滑到底，直到碰到墙壁边缘、棋盘边界或另一台机器人为止，中途不能停在空地上。
- 玩家可以借用其他颜色的机器人作为“垫脚石/挡板”，帮助目标机器人停在目标格。

# 操作与计分
- 每位玩家拥有独立的本地实验棋盘，可分步点击机器人并滑动、随时「撤销」上一步或「重置」回本局初始位置，也可直接提交完整路线或选择「放弃本局」。
- 当玩家将指定颜色的目标机器人停在目标格上时，自动锁定并提交当前步数的解法。
- 当所有玩家均解出或放弃后进行本局结算：
  - 本局步数最少（并列最佳）的玩家获得 +2 分；
  - 其他成功解出的玩家获得 +1 分；
  - 放弃或超时的玩家得 0 分。
- 随后主棋盘的 4 台机器人更新为本局最优解的终点位置，并在此基础上开启下一局目标（可选 5 局标准 / 3 局快速）。全赛程结束后按总积分、解出局数及总步数决出排名。
''';

const String nonogramRules = '''
# 数织竞速（Nonogram Race / Picross）

# 游戏概述
- 支持 1～6 人同场竞技的像素逻辑推理竞速游戏。
- 每局从趣味像素图案库（爱心、皇冠、小猫、飞船、帆船、音符、宝剑、松树、笑脸、钻石等）生成题目，并计算每一行与每一列的精确数字线索（如 `[2, 1]`、`[5]`、`[0]`）。

# 核心规则
- 行/列旁边的数字线索表示该行或该列中「连续涂黑格子的长度」及其先后顺序。
- 同一行/列若有多个数字（如 `2 1`），则这两组连续涂黑格之间至少相隔 1 个空白格；`0` 表示整行或整列没有任何涂黑格。
- 每位玩家在各自的独立网格上作答，单元格支持三种状态：
  - 空白（`0`）：尚未确定的格子；
  - 涂黑（`1`）：确定填充的像素格；
  - 标记 `X`（`2`）：辅助排除确定的空白格（不影响判定）。

# 判定与计分
- 一旦玩家棋盘上所有涂黑格（`1`）完全满足全部行线索与列线索，系统立即判定该玩家解出本题！
- 越早解出得分越高：第 1 名解出得 10 分，第 2 名得 8 分，第 3 名得 6 分，后续解出得 4 分；放弃本题得 0 分。
- 支持网格大小选择（`5×5 快速`、`7×7 标准`、`9×9 挑战`）与题数选择（`3 题` / `1 题`）。全部题目完成后按总分、解出题数与用时排名。
''';

const String sokobanRules = r'''
# 推箱子竞速（Sokoban Race）

# 游戏概述
- 支持 1～6 人同台竞速的经典仓库推箱子空间解谜游戏。
- 内置 16+ 个经过严格验证必有解的经典微缩仓库关卡（7×7 至 9×9），所有玩家在同一关卡下各自独立操作自己的仓库工人与箱子。

# 移动与推箱规则
- 工人（`@`）可向「上、右、下、左」四个方向移动一格：
  - 若前方是空地（`.`）或目标点（`G`），工人直接走入该格；
  - 若前方是箱子（`$`），且箱子正后方紧邻的一格不是墙壁（`#`）也没有其他箱子，则工人将箱子向前推动一格并走入原箱子所在格；
  - 不能拉拽箱子，也不能同时推动两个排成一列的箱子。
- 游戏支持无限次「撤销」上一步与一键「重置」本关，若陷入死角可随时回退或重来，也可选择「放弃本关」。

# 过关与计分
- 当玩家仓库中的所有箱子全部位于目标点（`G`）上时，立即完成本关！
- 按完成先后顺序获得基础竞速分（第 1 名 10 分、第 2 名 8 分、第 3 名 6 分、其余完成者 4 分），若推箱次数/总步数达到最佳标准还可获得额外 +1～+2 步数效率奖励分！
- 支持 `3 关标准` 与 `1 关快速` 模式，全部关卡结束后按总积分、通关数与总步数决出最终名次。
''';
