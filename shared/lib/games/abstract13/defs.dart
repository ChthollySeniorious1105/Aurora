const _punctRules = '''
# 概述
彭克特桥接棋（PÜNCT）是著名设计师 Kris Burm “星盘众棋计划（Project GIPF）”的收官之作。棋盘为半径 4 的正六角形（共 61 个六角格），正中央 7 个格子构成“中央禁区”，外围 6 条边构成 3 组相对的外边。

# 三六角棋子与 PÜNCT 点
- 黑白双方各拥有一套由 **3 个六角格**组成的棋子储备（标准模式每种形状各 6 枚共 18 枚，快速模式每种各 4 枚共 12 枚）。
- 棋子分为三种形状：**直线型（Straight）**、**折角型（Angled）**与**三角型（Triangle）**。
- 每枚棋子的中心格带有醒目的圆点标记，称为 **PÜNCT 点**，是棋子移动与叠放的基准核心。

# 回合行动（二选一）
1. **投放新棋子（Drop）**：从个人储备区选择一枚棋子，以任意旋转方向放置到棋盘上的 **3 个空格**上。注意：**新投放棋子的任何一个格子都不得进入中央 7 格禁区**！
2. **移动或叠放棋子（Move / Stack）**：选择棋盘上一枚未被其他棋子压住（三个格子均位于最顶层）的己方棋子，使其 **PÜNCT 点沿六角直线方向**滑行至目标格（可同时自由旋转棋子）：
   - **地面移动**：目标位置的 3 个格子必须全部为空格（允许进入或穿过中央禁区）；
   - **叠放与搭桥**：目标位置的 3 个格子全部位于已有棋子上方，且 **PÜNCT 点必须落在己方颜色的顶层格上**（其余两个卫星格可压住任意颜色的棋子）。

# 胜负条件
- 任何一方在回合结束时，若棋盘上处于**最顶层**的己方颜色格子形成一条连续相邻的通路，成功连接**任意一组相对的外边**，则该玩家立即获胜！
- 若储备耗尽或达到回合上限仍未分出胜负，则由控制更多中央禁区顶层格的玩家获胜（若仍平手则比较全盘顶层控制格数）。支持认输、求和与悔棋。
''';

