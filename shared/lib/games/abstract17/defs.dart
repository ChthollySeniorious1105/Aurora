const _kubaRules = '''
# 概述
库巴推球棋（Kuba，又名 Traboulet）是享誉世界的经典 `7×7` 弹球推挤抽象策略棋。双方在没有斜向移动的正交网格上，利用独创的**“后方留空推球法则（Open-Behind Push Rule）”**与**“劫争禁手（Ko Rule）”**，将中央十字菱形阵中的中立红球或敌方弹球推出棋盘边缘！

# 棋盘与初始设置
- 棋盘为 **7×7** 正交网格，初始共布置 **29 枚**弹球：
  - **白方（座位 0）**：左上 `(0..1, 0..1)` 与右下 `(5..6, 5..6)` 两个 `2×2` 角落，共 **8 枚白球**；
  - **黑方（座位 1）**：右上 `(0..1, 5..6)` 与左下 `(5..6, 0..1)` 两个 `2×2` 角落，共 **8 枚黑球**；
  - **中立红球**：棋盘中央曼哈顿距离 `|r - 3| + |c - 3| <= 2` 的十字菱形区域，共 **13 枚红球**。

# 后方留空推球法则（核心机制）
- 轮到你的回合时，选择棋盘上 **1 枚己方颜色的弹球 `(r, c)`** 以及 **1 个正交推动方向**（上、右、下、左），将该弹球连同其前方紧挨着的一整排连续弹球向该方向整体平移 **1 格**。合法推动必须同时满足以下 **3 项铁律**：
  1. **后方留空（Open-Behind）**：所选己方弹球 `(r, c)` 的**推动反方向紧邻格 `(r - dr, c - dc)` 必须为空格或位于棋盘边界之外**（即你只能从一排弹球的末端插入手指推动，不能从队列中间硬推）！
  2. **禁止自推出界（No Self-Ejection）**：整排弹球向前平移 1 格时，**绝不能将己方颜色的弹球推出 7×7 棋盘边界**！
  3. **劫争禁手（Ko Rule）**：推动后的棋盘整体状态，**不能与对手上一步行动之前的棋盘状态完全相同**（禁止你推过来、我立刻原样推回去的无限循环）！

# 夺球连击与胜负条件
- **连击奖励回合**：当你将一枚**中立红球**或**敌方弹球**推出 7×7 棋盘边界时，即将其捕获计入你的战利品，并且**立即获得一次额外奖励回合（Bonus Turn）继续行动**！
- **获胜条件**：率先捕获 **7 枚中立红球**（快速模式为 **5 枚**）、或将 **全部 8 枚敌方弹球**推出界外、或将对手完全封锁至无路可推的玩家立即获胜！支持认输、求和与悔棋。
''';

