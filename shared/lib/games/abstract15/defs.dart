# 概述
三环同心棋（Otrio）是由 Marbles Brain Workshop 出品并斩获瑞典年度游戏大奖的现代抽象几何连珠棋。游戏将经典井字棋升级为 **3×3 同心三环立体槽位**，带来多维度、多尺度的空间封堵与连珠博弈。

# 棋盘与圆环储备
- 棋盘为 **3×3** 网格，每个格子内包含 **小环（0）、中环（1）、大环（2）** 三个同心圆环槽位（共 27 个槽位）。
- 支持 **2～4 人**同台竞技：每位玩家开局拥有专属颜色的 **3 枚小环、3 枚中环、3 枚大环**（共 9 枚圆环）。

# 回合行动
- 轮到你的回合时，从自己剩余的圆环储备中任选 **1 枚圆环**，放入棋盘上任意一个对应尺寸尚为空位的同心槽位 `(r, c, size)` 中。
- 圆环一旦落入槽位，整局对局中不可移动或替换。

# 三重即时获胜条件（满足任一立即获胜）
1. **同尺寸三连珠（Same-Size 3-in-a-Row）**：在横、竖、斜任意一条三格直线上，集齐 3 枚**颜色相同且尺寸完全相同**（全小、全中或全大）的己方圆环！
2. **大小渐进三连珠（Ordered-Size 3-in-a-Row）**：在横、竖、斜任意一条三格直线上，按**从小到大（`[小, 中, 大]`）或从大到小（`[大, 中, 小]`）**的严格顺序集齐 3 枚己方圆环！
3. **同格三环同心嵌套（Concentric Nest）**：在**同一个格子 `(r, c)`** 内同时集齐己方颜色的**小环、中环与大环**！
- 若所有槽位填满或全员无子可下仍无人达成连珠，则判为平局。支持认输、求和与悔棋。
