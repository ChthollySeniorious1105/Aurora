const _dipoleRules = '''
# 概述
偶极子棋（Dipole）是由著名抽象棋设计师 Mark Steere 创作的战术分堆吃子棋。双方在 **8×8** 国际象棋棋盘的 **32 个暗格（`(r + c) % 2 == 1`）** 上统领初始高度为 12 的叠子军团，展开前推分兵与全向回马枪吃子的深度较量。

# 初始设置
- 仅使用棋盘上的 **32 个暗格**。
- **白方（座位 0）**初始在底端 `(7, 4)` 拥有一整摞 **12 枚**棋子，推进方向向上（`dr < 0`）或横向（`dr == 0`）；
- **黑方（座位 1）**初始在顶端 `(0, 3)` 拥有一整摞 **12 枚**棋子，推进方向向下（`dr > 0`）或横向（`dr == 0`）。

# 暗格步距法则与回合行动
- 棋子只能沿着 **8 个方向（横、竖、斜）** 从一个暗格跳往另一个暗格（允许飞跃中途任何棋子）：
  - **斜向移动**：步距 `count = 1, 2, 3...` 格均落在暗格上；
  - **正交（横/竖）移动**：步距必须为偶数 `count = 2, 4, 6...` 格才能落在暗格上。
- 每回合从己方一个棋子堆 `(r1, c1)` 中分出 **`count >= 1` 枚棋子**，沿 8 个方向之一移动**恰好 `count` 格**至暗格 `(r2, c2)`（即 `max(|r2-r1|, |c2-c1|) == count`）：
  1. **前向/横向机动与合堆（`move`）**：方向必须为**正前方、斜前方或左右横向**（不可后退），且目标暗格 `(r2, c2)` 为**空格或己方棋堆**（分出的 `count` 枚棋子直接并入目标格己方棋堆）。
  2. **全向强袭吃子（`capture`）**：可朝 **8 个方向的任意方向（包括向后或斜后方！）** 发起攻击，前提是目标暗格 `(r2, c2)` 上为**敌方棋堆且敌方叠子数 `<= count`**！吃子后移除该格全部敌子，并由这 `count` 枚进攻棋子占领该格。

# 胜负条件
- 率先**歼灭全部敌方棋子**，或令对手在回合开始时**无合法行动**者立即获胜！支持认输、求和与悔棋。
''';

const _slitherRules = '''
# 概述
蜿蜒连边棋（Slither）是由 Corey Clark 设计的现代高口碑拓扑连接抽象棋。游戏通过一条简洁却极具空间张力的**“禁斜角孤立接触铁律（No-Diagonal-Crosscut Invariant）”**，结合每回合“滑移旧子 + 放置新子”的双重机动，彻底消除了传统网格连边棋的平局死锁。

# 棋盘与连通目标
- 标准模式使用 **7×7** 正方棋盘，快速模式使用 **6×6** 正方棋盘。
- **白方（座位 0）**的目标是用己方棋子通过**上下左右正交相邻**连成一条贯通**顶边（第 1 行）与底边（第 N 行）**的通路；
- **黑方（座位 1）**的目标是用己方棋子通过**上下左右正交相邻**连成一条贯通**左边（第 1 列）与右边（第 N 列）**的通路。

# 回合流程（可选滑移 + 必须落子）
- 轮到你的回合时，在一个动作中依次完成：
  1. **可选滑移（Slide）**：你可以选择棋盘上已有的 **1 枚己方棋子**，向周围 8 个方向（正交或斜向）滑移 **`1` 格**至相邻空格（也可以跳过滑移，令 `fromR = -1`）。
  2. **必须落子（Place）**：在棋盘任意空格 `(placeR, placeC)` 上放置 **1 枚新的己方棋子**。

# 禁斜角孤立接触铁律（核心合法性判定）
- 在你完成本回合的滑移与落子后，棋盘上所有的己方棋子必须满足：
  - **任意两枚呈对角线斜向相邻的同色棋子 `(r, c)` 与 `(r+1, c±1)`，它们的两个公共正交邻格 `(r, c±1)` 与 `(r+1, c)` 中，必须至少有一格也放有同色棋子！**
  - 换言之，同色棋子绝不允许出现“仅有斜角尖端相碰而无正交桥接”的孤立斜接形态（但你可以通过先滑移一枚旧子再落入新子，在回合结束瞬间化解斜角冲突并重构连线！）。

# 胜负条件
- 率先在自己负责的两条对边之间建立一条**四向正交连通链**的玩家立即获胜！支持认输、求和与悔棋。
''';

