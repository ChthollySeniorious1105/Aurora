const _wuhanRules = '''
# 武汉麻将（红中赖子杠）
4 人对局，使用万、筒、条、风牌（东南西北）、箭牌（白发中）共 136 张牌。庄家起手 14 张，闲家 13 张，可吃（仅上家）、碰、杠。
# 翻赖子与特殊杠（红中 / 发财 / 赖子杠）
- 每局发牌后从牌墙翻出 1 张指示牌（赖子皮），按同花色或风箭顺序的下一张即为本局【赖子】（百搭牌）。
- 红中（7z）固定为特殊杠牌，不能作为赖子；若翻出白板（5z）则发财（6z）为赖子，若翻出发财（6z）或红中（7z）则以白板（5z）作为赖子。
- 赖子在手牌中可代替任意一张牌参与组合面子与将牌。
- 轮到自己出牌时，手牌中的【红中（7z）】、【发财（6z）】或【赖子】均可随时声明特殊杠（赖子杠）：亮出该张牌，本局自身番数倍率翻倍（×2），并立即从牌墙补摸 1 张牌！
# 开口与二五八将
- 开口规则：默认【必须开口】（至少吃、碰或明杠 1 次后才允许胡牌，暗杠或红中/发财/赖子杠不算开口）；也可在房间选项中切换为【可门清】。
- 二五八将：普通平胡（小胡）要求 4 组面子 + 1 对将牌，且将牌必须是万、筒、条中的 2、5 或 8。
- 大胡牌型（无需二五八将）：碰碰胡、清一色、将一色（全部由 2/5/8 组成）、风一色（全部由字牌组成）、全求人，以及杠上开花、抢杠胡、海底捞月。
# 计分与局数
- 平胡基础 1 番（无赖子硬胡翻倍），大胡每项 4 番，自摸翻倍，庄闲翻倍，再乘以赢家与付款双方的杠牌番数倍率（红中杠、发财杠、赖子杠、明暗杠每次 ×2）。
- 支持 4 局东风战与 1 局快速模式，按累计总分排名。
''';

const _xueliuRules = '''
# 血流成河麻将
4 人对局，仅使用万、筒、条共 108 张数牌，无字牌。不可吃牌，可碰、杠、胡。
# 开局换三张与定缺
- 换三张：开局每位玩家从手牌中选出 3 张同花色的牌，按随机方向（下家、对家或上家）同时交换。可在选项中关闭。
- 定缺：所有玩家各自选择万（m）、筒（p）、条（s）中的一门作为本局缺门。手牌中保有缺门花色时必须优先打出缺门牌，且持有缺门牌期间不能胡牌。
# 血流成河连续胡牌
- 与“血战到底”胡牌后离场不同，在【血流成河】中，玩家自摸或点炮胡牌后【立即结算收分，但继续留在场上】！
- 首次胡牌后玩家手牌即进入【锁定状态】（不能再改听或碰牌）：
  - 后续轮到该玩家摸牌时，若摸到所听的牌可再次声明【自摸胡牌】并再次收分！
  - 若摸到的牌能升级已有的碰牌（补杠）或构成不改变听口的暗杠，可开杠补牌；否则必须将刚摸到的牌直接打出。
  - 其他玩家打出该玩家所听的牌时，已胡牌玩家同样可以继续【点炮胡牌】！
- 一局牌将持续进行，直到牌墙所有牌完全摸空为止，单局可胡牌十余次！
# 牌墙摸空结算：查花猪、查大叫与退税
- 查花猪：摸完最后一张牌时，手牌仍有缺门花色者为“花猪”，向每位非花猪玩家赔付封顶番数分数。
- 查大叫：未听牌（且非花猪）的玩家向每位已听牌玩家赔付其最大可能番数的分数。
- 退税：未听牌玩家退还本局刮风下雨所得杠钱。
''';

