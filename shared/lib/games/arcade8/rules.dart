# 游戏概述
- 支持 1～6 人同场竞速的经典「交叉数字填字」逻辑推理游戏（数和 / Kakuro / Cross Sums）。
- 棋盘（`5×5 快速` 或 `6×6 标准`）由两类格子组成：
  - `黑色斜线线索格（Black Clue Cells）`：位于第 0 行、第 0 列以及盘面内部分隔处。右上角数字代表其右侧连续白格的「横向总和（acrossSum）」，左下角数字代表其下方连续白格的「纵向总和（downSum）」。
  - `白色填数格（White Entry Cells）`：供玩家填入数字 `1～9`。

# 填数核心规则
- 玩家选中任意白色格子后，可通过数字键盘（或键盘按键 `1～9`）填入数字，或按清除键置空。
- 一个合法的数和解必须同时满足以下三条黄金条件：
  - `全盘填满`：所有白色填数格均已填入 `1～9` 的数字；
  - `行列区段和精确匹配`：每一段连续的横向白格之和必须**严格等于其左侧黑格右上角的横向线索数**，每一段连续的纵向白格之和必须**严格等于其上方黑格左下角的纵向线索数**；
  - `同段数字绝不重复`：同一段连续横向白格内部、以及同一段连续纵向白格内部，**绝对不能出现重复的数字**（例如横向和为 `4` 的两格只能填 `1+3` 或 `3+1`，不能填 `2+2`）！

# 判定与计分
- 当玩家的填数同时满足上述全部条件时，立即完成本题并获得竞速积分：第 1 名 10 分、第 2 名 8 分、第 3 名 6 分、后续解出者 4 分；放弃本题得 0 分。
