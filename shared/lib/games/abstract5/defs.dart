const _fanoronaRules = '''
# 概述
马达加斯加棋（Fanorona）是流传于马达加斯加岛的传统国粹级连线吃子策略棋，以独特的“撞击吃（Approach）”与“后撤吃（Withdrawal）”远程成串消子机制以及华丽的连续追击连招享誉世界抽象棋坛！

# 棋盘规格与强弱交点（选项）
- 9×5 标准模式（Fanorona-Tsivy）：9 列 5 行共 45 个交点，开局双方各有 22 枚棋子，正中央 E3 交点为空。
- 5×5 快速模式（Fanorona-Dimy）：5 列 5 行共 25 个交点，开局双方各有 12 枚棋子，正中央 C3 交点为空。
- 强交点与弱交点：棋盘上带有斜线穿过的交点（行列坐标之和为偶数）称为【强交点】，可沿横、竖、斜 **8 个方向**移动；仅有横竖线穿过的交点称为【弱交点】，只能沿横、竖 **4 个方向**移动。

# 撞击吃与后撤吃机制
每一步棋子只能沿棋盘实线向相邻的空交点移动 1 步（设移动方向向量为 d）：
- 撞击吃（Approach Capture）：移动到达新交点后，若沿移动方向正前方紧邻的第 1 个交点上有敌方棋子，则将该敌子以及其后方沿同一条直线**连续紧挨着的所有敌方棋子**一并消灭移除！
- 后撤吃（Withdrawal Capture）：离开原交点时，若沿移动反方向紧邻的第 1 个交点上有敌方棋子，则将该敌子以及其后方沿同一条直线**连续紧挨着的所有敌方棋子**一并消灭移除！
- 二选一抉择：若某一步移动同时满足【撞击吃】与【后撤吃】，玩家必须从中**选择其中一种**执行（不能在同一步内前后通吃）。
- 有吃必吃：在回合开始时，若棋盘上存在任何可以吃子的走法，则**必须走吃子步**；只有当没有任何棋子能吃子时，才允许走不吃子的普通移动（称为 Paika）。

# 连续追击（Capturing Chain）
- 当你的某枚棋子完成一次吃子后，如果**同一枚棋子**在当前位置还能继续走出新的吃子步，你可以选择继续移动它进行连环追击，也可以随时点击“结束追击”将回合交还对手。
- 连续追击限制：在同一个回合的连续追击过程中，该棋子**不能重复踏入本回合已经走过的交点**，也**不能连续两步沿完全相同的方向前进**。

# 胜负条件
- 全歼获胜：将对手棋盘上的所有棋子全部吃光（或令对手无路可走）者立即获胜！支持悔棋、认输与求和。
''';

