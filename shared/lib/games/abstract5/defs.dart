# 概述
塔克棋（Tak）是由 James Ernest 与奇幻作家 Patrick Rothfuss（《弑君者传奇》作者）于 2016 年共同设计的现代抽象策略棋经典。双方通过放置平石、立石与顶石，或抓起叠堆沿直线分撒棋子，争夺棋盘控制权并铺设连通对边的大道！

# 棋盘规格与储备（选项）
- 5×5 标准模式：每位玩家拥有 21 枚常规石子 + 1 枚顶石（Capstone）。
- 4×4 快速模式：每位玩家拥有 15 枚常规石子 + 1 枚顶石（Capstone）。

# 三种棋子形态
1. 平石（Flat Stone）：平放的常规石子。**计入修路连通**，也可以在平局或终局时计入平石控制分；其他任何棋子都可以移动到平石上方形成叠堆。
2. 立石 / 墙（Standing Stone / Wall）：竖立放置的常规石子。**不计入修路连通**，且能阻挡任何其他棋子叠放到它上面（唯一的例外是被顶石单独压平）。
3. 顶石（Capstone）：造型高耸的王牌棋子。**计入修路连通**，且任何棋子都不能叠放到顶石上面；当顶石在分堆移动的**最后一步单独（仅此 1 枚顶石）**落在一枚立石（墙）上时，会将该立石当场**压平（Flatten）**变成平石，并占据该叠堆顶端！

# 回合流程
- 开局首回合特殊规则（前 2 手）：在双方各自的第 1 个回合（即整局的前两步），你必须在任意空格上放置 1 枚**对手颜色**的平石！从第 3 手起，双方恢复操作各自颜色的棋子。
- 常规回合二选一：
  1. 放置棋子（Place）：从你的储备中取 1 枚棋子，选择以【平石】、【立石】或【顶石】形态放置在棋盘任意**空格**上。
  2. 分堆移动（Spread）：选择棋盘上**最顶端棋子属于你**的任意一处棋子叠堆，从顶部拿起 1 至 N 枚棋子（N 为棋盘边长上限，即 4 或 5），向北、东、南、西四个正交方向之一沿直线推进，并在沿途经过的每一个连续格子上**至少从手底落下 1 枚棋子**，直到手中棋子全部落完。

# 胜负条件
- 大道获胜（Road Win）：率先用栈顶属于自己的【平石】与【顶石】在正交（上下左右）方向上铺出一条连接**北边与南边**或连接**西边与东边**的连续通路者，立即获胜！（若一次分堆移动同时为双方铺通大道，则当前行动方优先获胜）。
- 平石决胜（Flat Win）：当任意一方储备棋子全部耗尽，或棋盘所有格子均被占满时，统计棋盘上栈顶为【平石】的格子归属数量，控制更多平石者获胜！支持悔棋、认输与求和。
