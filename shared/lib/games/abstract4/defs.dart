const _amazonsRules = '''
# 概述
亚马逊棋（Game of the Amazons）是由阿根廷棋手 Walter Zamkauskas 于 1988 年发明的经典领地封锁抽象策略棋。黑白双方在 8×8 或 10×10 棋盘上各操控 4 名亚马逊女战士，每回合移动女战士并发射火焰箭永久封锁棋盘格，将对手所有女战士围困至无路可走者获胜！

# 开局布置
- 每位玩家拥有 4 枚亚马逊女战士棋子，开局对称分布在棋盘四侧，白方先行。
- 8×8 快速模式：白方位于 C1、F1、A3、H3；黑方位于 C8、F8、A6、H6。
- 10×10 标准模式：白方位于 D1、G1、A4、J4；黑方位于 D10、G10、A7、J7。

# 回合流程
每回合当前玩家必须依次完成两个步骤：
1. 移动女战士：选择己方 1 枚亚马逊女战士，沿横、竖、斜八个方向之一作直线移动任意格数（如同国际象棋的“后”），必须停在空格上，且途中不能越过或停留在任何女战士或已被箭矢封锁的格子上。
2. 发射火焰箭：使用刚刚移动过的这名女战士，从其新落点出发，同样沿横、竖、斜八个方向之一作直线发射 1 支火焰箭（途中不能越过任何女战士或已有箭矢格，但可以射回或穿过刚才离开的起点格）。箭矢落点将被永久封锁，整场对局中任何女战士与箭矢都不能再进入或穿过该格。

# 胜负条件
- 困毙获胜：轮到某一方行动时，若其全部 4 枚亚马逊女战士均被围困，无法完成任何合法的“移动+射箭”，则该玩家立即落败，对手获胜！
- 支持悔棋、认输与求和。
''';

const _loaRules = '''
# 概述
行动线棋（Lines of Action，简称 LOA）是由著名桌游设计师 Claude Soucie 创作的经典八方向连线策略棋。在 8×8 棋盘上，黑白双方各有 12 枚棋子，黑方先行。每一步的移动距离由该整条直线上的棋子总数决定，率先将己方棋盘上所有剩余棋子连成单一八方向连通块者立即获胜！

# 开局阵型（选项）
- 标准边框列阵（Standard）：黑方 12 子排在上下底边（第 1、8 行的 B~G 列），白方 12 子排在左右侧边（A、H 列的第 2~7 行），四角为空。
- 交错列阵（Scrambled）：四条边框上的 24 枚棋子按黑白交替间隔排列，开局即相互牵制。

# 行动线移动规则
每回合选择己方 1 枚棋子，向横、竖、斜八个方向之一作直线移动：
- 步数等于线上总子数：你在某个方向上移动的格数，必须**严格等于该棋子所在整条直线上（含正反两个方向）当前所有黑子与白子的总数**！
- 越子限制：移动途中可以跳过**己方**棋子，但**绝不能**跳过**对方**棋子。
- 落点与吃子：目标格可以是空格；若目标格上有 1 枚对方棋子，则将其吃掉并移出棋盘；目标格不能是己方棋子。

# 胜负条件
- 连成一片获胜：当一方在棋盘上的所有剩余己方棋子在横、竖、斜八方向上彼此相连形成**唯一一个连通整体**时，该玩家立即获胜！（若僅剩 1 枚棋子也视为已连成一片）。
- 同时连通判定：若主动吃掉对方孤子后，导致双方同时达成单连通，则**本回合行动方优先获胜**；若仅令对方剩余棋子达成单连通，则对方获胜。
- 若一方无合法移动或达到 160 手回合上限，则按连通分块数更少者获胜（若分块数相同则比较最大连通块棋子数，仍相同则判和）。
- 支持悔棋、认输与求和。
''';

const _kamisadoRules = '''
# 概述
神道棋（Kamisado）是由 Peter Burley 设计的经典无吃子颜色锁抽象棋。8×8 棋盘由 8 种颜色（橙、蓝、紫、粉、黄、红、绿、棕）按拉丁方阵规律铺就，双方各拥有 8 座对应颜色的龙塔。你每一步落点格子的颜色，将强制决定对手下一步必须移动哪一座龙塔！

# 移动与颜色锁规则
- 开局布置：双方 8 座不同颜色的龙塔分别立于各自底线（第 1 行与第 8 行）对应颜色的格子上。
- 首步自由：每局的第一步，先手玩家可以任选己方 8 座龙塔中的任意 1 座进行移动。
- 前进规则：龙塔只能向**正前方**、**左前方**或**右前方**三个方向作直线移动任意格数（至少 1 格），途中不能越过或停留在任何已有龙塔的格子上。神道棋中**没有吃子**。
- 颜色锁联动：当你的龙塔停在某个颜色的棋盘格上时（例如停在【红格】），对手下一回合**必须**移动他自己的【红塔】！

# 阻挡跳过与死锁判负
- 被阻挡跳过（Pass）：若你本回合被指定必须移动的那座龙塔前方三路均被堵死（0 个合法落点），你必须点击“跳过回合”。该龙塔留在原地不动，并以**该龙塔当前脚下棋盘格的颜色**作为对手下一回合必须移动的龙塔颜色！
- 死锁循环判负：若某一步移动导致双方龙塔进入互相锁死的无限跳过循环（没有任何一方能移动），则**走最后一步导致该死锁循环的玩家立即判负**，对手赢得本局！

# 胜负与赛制（选项）
- 达阵获胜：率先将己方任意 1 座龙塔移动到**对方底线**者立即赢得本局（得 1 分）！
- 单局决胜（1分）：赢下 1 局即获胜。
- 三局积分制（3分）：每局达阵或令对手死锁得 1 分，败方在下一局执先手，率先累计获得 3 分者赢得整场对局！
- 支持悔棋、认输与求和。
''';

