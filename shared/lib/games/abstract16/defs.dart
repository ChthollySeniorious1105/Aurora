const _tumbleweedRules = '''
# 概述
风滚草视线棋（Tumbleweed）是由 Michaela 创作并斩获 **2020 年 BGG 金极客年度最佳抽象棋（Golden Geek Best Abstract Game）** 的现代经典六角网格策略名作。游戏通过独树一帜的“六向视线计数定居与叠高吞并法则”，将空间视线阻挡、制高点争夺与围棋式领地围控融为一体。

# 棋盘与初始设置
- 标准模式使用半径为 **4**（共 **61 格**）的正六边形棋盘；快速模式使用半径为 **3**（共 **37 格**）的正六边形棋盘。
- 初始布置：
  - 中心格 `(0, 0)` 放置一座高度为 **2** 的**中立棋堆**；
  - `(-1, 0)` 放置一座高度为 **1** 的**红方（座位 0）棋堆**；
  - `(1, 0)` 放置一座高度为 **1** 的**白方（座位 1）棋堆**。

# 视线定居与吞并法则（Line-of-Sight Settlement）
- 对棋盘上任意六角格 `(q, r)`，沿 **6 个正六角直线方向**向外发射视线（每条视线遇到**第一个非空格**即停止——无论该格上是己方、敌方还是中立棋堆），统计这 6 条视线上能看到的**己方棋堆总数 `losCount`**。
- 轮到你的回合时，你可以选择定居（`settle`）或跳过（`pass`）：
  - 你可以在目标格 `(q, r)` 定居，当且仅当 **`losCount >= 1` 且 `losCount > 目标格当前高度`**！
  - 定居成功后，移除目标格原有的任何棋堆（无论空格、中立、敌方或己方旧堆），并在 `(q, r)` 放置一座高度恰好等于 **`losCount`** 的己方棋堆！

# 终局与领地计分
- 当某一方直接占领超过棋盘总格数的一半，或双方连续跳过（Pass）时，对局立即结束。
- 每位玩家最终得分 = **己方棋堆占领的格数** + **仅被己方棋堆视线看到的空六角格数**（即己方视线数 `> 0` 且敌方视线数 `== 0` 的受控领地）！总分更高者获胜。支持认输、求和与悔棋。
''';

