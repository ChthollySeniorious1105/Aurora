# 棋盘与回合落子配额
- 标准模式使用半径为 **4**（共 **61 格**）的正六边形棋盘；快速模式使用半径为 **3**（共 **37 格**）的正六边形棋盘。
- **首回合（Turn 1）**：先手（座位 0）在棋盘任意空格放置 **1 枚**棋子（`quota = 1`）。
- **后续回合**：当前行动玩家在空六角格上放置 **`1..quota` 枚**己方棋子（默认配额 **`quota = 2`**；若想在未放满配额时提前结束回合，可在至少放置 1 枚棋子后点击“结束回合”）。

# 成大群触发三子追赶法则（核心机制）
- 在玩家回合开始时，记录其当前最大同色相连棋群的规模 `startMax`。
- 在玩家回合结束时，计算其最新最大同色相连棋群规模 `endMax` 以及对手当前最大同色相连棋群规模 `oppMax`。
- **若 `endMax > startMax` 且 `endMax >= oppMax`**（即该玩家在本回合中扩大或新建了一个同色连通群，使其规模追平甚至超越了对手的最大连通群），则**对手在紧接着的下一回合获得 `quota = 3` 枚棋子的追赶配额**（否则对手下一回合配额仍为 `quota = 2`）！

# 终局字典序计分决胜
- 当棋盘上所有六角格全部填满时对局结束。
- 分别统计双方各自所有同色连通群的大小，并按**从大到小降序排列**进行逐位比较：第一个大小出现差异的位次上，群规模更大的一方立即获胜（奇数总格数保证绝无平局）！支持认输、求和与悔棋。
''';

