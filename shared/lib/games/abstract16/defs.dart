# 正交求和强制吞并法则（Mandatory Pip-Sum Capture）
- 轮到你的回合时，任选棋盘上一个**空格 `(r, c)`**，观察其上下左右（最多 4 个）正交相邻格中已有的骰子集合 `N(r, c)`：
  1. **强制吞并落子（合成 2～6 点）**：若 `N(r, c)` 中存在**至少一个包含 `>= 2` 枚骰子（无论敌我颜色！）且点数之和 `sum(S) <= 6` 的子集 `S`**，你在该空格落子时**必须**选择这样一个子集 `S`（2、3 或 4 枚相邻骰子），将 `S` 中的骰子全部移出棋盘，并在 `(r, c)` 放置一枚**点数等于 `sum(S)`** 的己方骰子！
  2. **普通落子（放置 1 点）**：仅当 `N(r, c)` 中**没有任何 `>= 2` 枚相邻骰子的点数之和 `<= 6`** 时，你在 `(r, c)` 放置一枚点数为 **`1`** 的己方骰子！
