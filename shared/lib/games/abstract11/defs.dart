焦点叠塔棋（Focus / Domination）是传奇设计师 Sid Sackson 荣获 1981 年德国年度游戏奖（Spiel des Jahres）的经典抽象策略棋。通过移动棋塔控制步数、利用“五层溢出”回收储备子并俘获敌方棋子。

# 棋盘与叠塔控制权
- 标准模式为切去四角三角形的 8×8 棋盘（共 52 个有效格），快速模式为 6×6 棋盘（36 格），开局在中央 6×6 区域对称放置 18 枚白子与 18 枚黑子。
- 每个格子可以叠放至多 5 枚棋子。**一座叠塔由最顶层棋子的颜色所属玩家控制**。

# 回合行动（二选一）
1. **移动叠塔**：选择一座由你控制的叠塔，从顶部拿起 `k` 枚棋子（`1 <= k <= 当前塔高`），沿正交方向（上、下、左、右）精确移动 `k` 步，落到目标格顶部。
2. **投放储备子**：若你的储备区有棋子，可将 1 枚储备子直接放到棋盘上**任意有效格**（空格、己方塔顶或敌方塔顶均可）。

# 五层溢出规则
- 移动或投放后，若目标格的叠塔高度超过 5 层，则从**塔底**逐枚移除多余棋子，直到塔高恢复为 5 层：
  - 底部溢出的**己方棋子**进入你的**个人储备区**（后续回合可随时空投）；
  - 底部溢出的**敌方棋子**被你**永久俘获**！

# 胜负条件
- 率先永久俘获指定数量敌方棋子（标准模式 6 枚 / 快速模式 4 枚）的玩家立即获胜；
- 若对手回合开始时既没有受控叠塔也没有储备子可投，你也立即获胜。支持认输、求和与悔棋。
''';

