const _gipfRules = '''
# 概述
吉普夫棋（GIPF）是设计师 Kris Burm 著名的“星盘众棋计划（Project GIPF）”旗舰之作。棋盘由半径为 3 的 37 个内部六角格，以及外围半径为 4 的 24 个边缘推入点组成。

# 初始设置
- 棋盘第 3 圈的 6 个角点交替放置 3 枚白子与 3 枚黑子。
- 每名玩家拥有个人储备区（标准模式 15 枚 / 快速模式 12 枚）。白方先行。

# 回合流程
1. **边缘推入**：从外圈 24 个入口点中选择一个，将储备区中的 1 枚己方棋子沿六角轴线推入相邻的内部格。
2. **整排推移**：若推入方向上有连续的棋子，整条连续棋子向内顺移 1 格，直到推入第一个空格；若该条直线直到对面边缘已全部塞满，则禁止沿该方向推入。
3. **四连消除与回收**：推动结束后，若任意六角直线上出现 **4 枚或以上同色连续棋子**：
   - 将这组四连棋子，以及同一直线上与它直接相连的所有棋子（不论黑白）一并移出棋盘；
   - 属于四连达成方的棋子**回收至其个人储备区**（循环再用）；
   - 属于对手的棋子则被**永久俘获**，不再回到游戏中。

# 胜负条件
- 任何玩家在自己的回合开始时，若个人储备区棋子数为 0，则立即判负！
- 支持认输、求和与悔棋。
''';

const _focusRules = '''
