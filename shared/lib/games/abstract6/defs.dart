# 五连计分与星环牺牲
- 每次移动并完成翻转后，检查棋盘任意直线方向上是否出现了**同色连续 5 枚标记**：
- 若形成五连（若同一步双方均形成五连，先结算当前行动方）：
  - 将这 5 枚连成一线的标记移出棋盘；
  - 达成五连的玩家获得 **+1 枚战利星环（计 1 分）**，同时必须将自己棋盘上的 1 枚星环移除作为奖杯。

# 胜负条件与选项
- 3 环标准模式：率先集齐 **3 枚**战利星环者立即获胜！
- 1 环闪电战模式：率先集齐 **1 枚**战利星环者立即获胜！
- 若一方无合法移动或达到回合上限，按已获战利星环数（平手则比拼盘面己方标记数）决出胜负。支持悔棋、认输与求和。
