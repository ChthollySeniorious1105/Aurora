# 概述
星盘棋（YINSH）是比利时著名设计师 Kris Burm“星盘计划（Project GIPF）”系列的压轴巅峰代表作，长期位居 BoardGameGeek 抽象策略棋排行榜前列。棋盘为 61 格正六边形星盘，双方通过移动“星环”留下并翻转“双色标记”，但每当你达成一次五连得分，就必须从棋盘上永久移除自己的一枚星环——越接近胜利，你手中的机动力量反而越少！

# 游戏阶段与核心规则
1. 布环阶段（Setup）：
   - 对局开始时星盘为空，白方与黑方轮流在任意空位上放置星环，直到双方各放满 **5 枚星环**（共 10 枚）。
2. 行棋阶段（Play）：
   - 轮到你时，选择自己棋盘上的任意 1 枚【星环】，沿六边形的 **6 个直线方向之一**移动：
   - 留下标记：星环离开起点时，会在**原起点位置留下 1 枚你所属颜色的标记**。
   - 移动与跳子限制：
     - 星环在移动途中**绝对不能跳过或停留在任何星环上**。
     - 星环可以沿直线经过任意数量的空位；
     - 若星环在途中跳过了 **1 枚或多枚连续紧挨着的标记**，则它**必须立即停在这串连续标记后方的第 1 个空位上**（不能跳过两串标记之间的空隙继续前进）。
