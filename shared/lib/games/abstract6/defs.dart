奇索棋（Quixo）是由法国著名设计师 Thierry Chapeau 创作并荣获法国戛纳国际游戏节金奖（As d'Or）的经典五子推盘抽象棋。棋盘由 5×5 共 25 枚立体木块组成，结合了井字连线与动态滑块移位机制，局势瞬息万变！

# 方块状态与拿取规则
- 棋盘上的 25 枚方块共有三种顶面状态：空白、✕（先手方符号）、◯（后手方符号）。开局时全部 25 枚方块均为空白。
- 轮到你行动时，你必须从棋盘**最外圈的 16 个边框位置**（第一行、最后一行、第一列或最后一列，内部 3×3 的 9 枚方块不可直接拿取）中，挑选并拿起 1 枚**顶面为空白**或**顶面已经是你自己符号**的方块（绝不能拿取对手符号的方块）。

# 推入与移位机制
- 拿起外圈方块 `(r, c)` 后，将其顶面朝上置为**你自己的符号（✕ 或 ◯）**；
- 接着，从该方块所在**同一行的左端/右端**或**同一列的上端/下端**（除原位置 `(r, c)` 本身外的 2 至 3 个端点之一）将该方块推回棋盘！
- 原先位于缺口与推入端之间的方块会沿直线向缺口方向顺移 1 格，从而同时改变整条行或列的棋子排布。

# 胜负条件（含官方“乌龙致负”铁律）
- 率先在横、竖或两条主对角线上将 **5 枚己方符号连成一线**者获胜！
- **官方特别规则**：如果某位玩家在推入方块时，不小心使**对手的符号**连成了五子一线（哪怕同一步也使自己的符号连成五子一线），也判定**对手立即获胜**！支持悔棋、认输与求和。
''';

