# 概述
大炮棋（Cannon）是由 David Whitcher 设计、并荣获思维运动奥林匹克（Mind Sports Olympiad）奖牌的现代战术抽象棋名作。游戏结合了隐蔽的底线王城部署、近战冲锋、战术跃退与独创的“三子连珠火炮（3-Soldier Cannon）”远程轰击机制。

# 初始阵列与王城部署
- 标准模式使用 **10×10** 棋盘（双方各 15 名士兵），快速模式使用 **8×8** 棋盘（双方各 12 名士兵）。
- **蓝军（座位 0）**士兵初始交错排列在底端前方的 3 行（`N-4..N-2` 行奇数列），推进方向向上（`dr = -1`）；
- **红军（座位 1）**士兵初始交错排列在顶端前方的 3 行（`1..3` 行偶数列），推进方向向下（`dr = +1`）。
- **第一回合部署王城（`place_town`）**：蓝红双方依次在各自底线（蓝方第 `N-1` 行，红方第 `0` 行）的非角落格（第 `1..N-2` 列）部署 1 座不可移动的 **🏰 王城（Town）**。

# 回合行动（进入战斗阶段后，每回合任选其一）
1. **士兵步进（Step）**：将 1 名己方士兵向前或斜前方（3 个方向）迈进 `1` 格至**空格**。
2. **近战吃子（Capture）**：将 1 名己方士兵向前、斜前方或左右横向（共 5 个方向）移动 `1` 格，吃掉该格上的敌方士兵或直接攻陷敌方 **🏰 王城**！
3. **战术撤退（Tactical Retreat）**：若 1 名己方士兵周围 8 格内紧邻至少 1 名敌方士兵，该士兵可向后或斜后方（3 个方向）连续跃退 **`2` 格**（中途格与目标格均须为空格）。
4. **三连火炮滑行与炮击（3-Soldier Cannon）**：
   - 任意 **3 名在横、竖或斜方向上紧邻连成一线**的己方士兵即组成一门**三连火炮**！
   - **火炮滑行（Cannon Slide）**：将三连火炮队尾的士兵沿队列方向直接移至炮口前方第 `1` 格空位（使整门火炮向前滑行 1 格）。
   - **远程炮击（Cannon Shoot）**：若三连火炮炮口正前方第 `1` 格为**空格**（作为隔山炮架空间），火炮无需移动即可开火，直接轰碎炮口前方第 **`2` 格或第 `3` 格**上的敌方士兵或敌方 **🏰 王城**！

# 胜负条件
- 率先通过近战吃子或远程炮击摧毁敌方 **🏰 王城**，或歼灭/困毙全部敌方士兵者立即获胜！支持认输、求和与悔棋。
