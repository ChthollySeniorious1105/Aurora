双色花围棋（Blooms）是由著名抽象棋设计师 Nick Bentley 创作的双色六角围杀策略名作。每位玩家同时操控**两种不同颜色的花子**，通过同色连通花簇的“气（Liberty）”展开充满几何美感与战术组合的围猎。

# 棋盘与四色花子
- 标准模式使用半径为 4 的正六角棋盘（61 格，率先围杀 **15 颗**敌子获胜）；快速模式使用半径为 3 的正六角棋盘（37 格，率先围杀 **10 颗**敌子获胜）。
- **春花方（座位 0）**操控两种花色：**🌸 樱粉（1）**与 **🌺 赤红（2）**；
- **寒晶方（座位 1）**操控两种花色：**💠 冰蓝（3）**与 **🔮 靛紫（4）**。

# 回合流程
- **开局首手平衡**：整局游戏的第 1 回合，先手玩家只放置 **1 颗**己方任意花色的棋子。
- **常规双色落子**：从第 2 回合起，当前玩家每回合在空六角格上放置 **1 颗或 2 颗**花子——若放置 2 颗花子，**这两颗花子必须分别属于你的两种不同颜色**（每种颜色各下 1 颗；也可只下 1 颗后主动结束回合）。

# 花簇（Bloom）与无气提子
- **花簇（Bloom）**：棋盘上相互紧邻且**颜色完全相同**的一组连通棋子构成一个独立的“花簇”。注意：同一玩家名下的两种不同颜色（如樱粉与赤红）彼此独立，**不会**合并为同一个花簇共享气！
- **无气围杀**：每次落子及回合结束时，棋盘上所有**相邻空格数（气）为 `0` 的敌方花簇**会被立即提走俘获，并计入当前玩家的俘获总数。

# 胜负条件
- 率先俘获达到目标数量（标准模式 **15 颗** / 快速模式 **10 颗**）敌方花子的玩家立即获胜！支持认输、求和与悔棋。
''';

