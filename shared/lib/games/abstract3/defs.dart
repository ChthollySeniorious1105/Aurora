  1. 移动：将该工人移动到八方向相邻的一个无其他工人、且无穹顶的格子上。目标格子的建筑高度最多只能比当前所在格高 1 层（即最多向上攀爬 1 层，但可以平移或向下跳任意多层）。
  2. 建造：使用刚刚移动过的这名工人，在其新位置八方向相邻的一个无其他工人、且无穹顶的格子上加盖 1 层建筑（0→1→2→3→4 穹顶）。第 4 层为蓝色穹顶，加盖穹顶后该格封顶，任何工人不能再站上去或继续建造。

# 胜负与淘汰
- 登顶获胜：当你的工人在自己的回合中从较低处移动到第 3 层建筑上时，你立即赢得整场对局！
- 无路可走：若轮到某位玩家时，他的所有工人都无法完成合法的“移动+建造”，该玩家被淘汰出局（2 人局对手直接获胜；3 人局将该玩家的工人移出棋盘，剩余玩家继续对局，直至决出唯一胜者）。
- 支持认输、求和与悔棋。

