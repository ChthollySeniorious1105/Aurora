const _abaloneRules = '''
# 概述
大力士棋（Abalone）是经典的双人六角格推子抽象棋。棋盘为边长 5 的正六边形（共 61 格），黑白双方各有 14 枚棋子，黑方先行。率先将对方 6 枚棋子推出棋盘边缘者获胜！

# 开局阵型（选项）
- 传统排列（Standard）：双方棋子分别排列在棋盘上下两端的底线三行（5+6+3 共 14 枚）。
- 比利时菊花阵（Belgian Daisy）：双方在棋盘四个角的两处对角各摆放一朵 7 枚棋子组成的六角“菊花”阵型（7+7 共 14 枚），开局即短兵相接、攻防激烈。

# 移动与推子规则
每回合你可以选择 1 枚、或同一直线上连续相邻的 2~3 枚己方棋子，向六个六角方向之一整体移动 1 格：
- 单子移动：1 枚己方棋子移入相邻空格。
- 纵队推进（In-line）：2 枚或 3 枚连成一线的己方棋子沿其连线方向前进 1 格。
  - 若前方第一格为空格，则整列棋子前进 1 格。
  - 推子（Sumito）：若前方紧挨着同一直线上的 1~2 枚对方棋子，且己方连线棋子数严格大于对方被推棋子数（即 2 推 1、3 推 1、3 推 2；数量相等或更少不能推），并且对方被推棋子串正后方为空格或棋盘外（不能被己方或第 3 枚对方棋子挡住），即可将对方这串棋子一并向前推动 1 格！
  - 推出棋盘：当对方棋子被推向棋盘边缘外时，该枚对方棋子即被击落出局。
- 横队平移（Broadside）：2 枚或 3 枚连成一线的己方棋子向非连线的侧方同时平移 1 格。所有目标格必须全部为空格，横队平移不能推子。

# 胜负
- 率先将 6 枚对方棋子推出棋盘者立即获胜！
- 若达到 200 手仍未满 6 枚，则按已推出对方棋子较多者获胜；若数量相同则判和。
- 支持认输、求和与悔棋。
''';

