圣托里尼（Santorini）是 2~3 人的立体建筑策略棋。在 5×5 的爱琴海岛屿棋盘上，每位玩家指挥 2 名工人移动并建造白墙与蓝顶（1~3 层建筑及第 4 层穹顶），率先让自己的工人踏上第 3 层建筑顶端者立即获胜！

# 流程
- 放置阶段：游戏开始时，按座位顺序每人在棋盘任意空格上放置自己的 2 名工人。
