- 阿尔忒弥斯（狩猎女神）：你的工人在移动阶段可以移动 1 步或连续移动 2 步（第 2 步不能移回起始原格）。
- 雅典娜（智慧女神）：若你的工人在本回合移动时向上攀爬了，则直到你的下一回合开始前，所有其他玩家的工人都不能向上攀爬。
