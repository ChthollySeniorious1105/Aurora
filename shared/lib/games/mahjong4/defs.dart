const _guizhouRules = '''
# 贵阳捉鸡麻将（通行豆 · 冲锋鸡 · 翻鸡）
4 人对局，仅使用万、筒、条共 108 张数牌（无风牌、箭牌）。不可吃牌，可碰、杠、胡。
# 通行豆（闷豆 / 转弯豆 / 点豆）与通行证规则
- 闷豆（暗杠）：手牌 4 张相同暗杠，获得 1 颗豆，三家各立即赔付 2 分。
- 转弯豆（补杠）：已碰牌再摸到第 4 张补杠，获得 1 颗豆，三家各立即赔付 1 分。
- 点豆（明杠）：对别人打出的牌明杠，获得 1 颗豆，点杠者立即赔付 1 分。
- 通行证规则（点炮限制）：普通平胡手牌若想点炮胡牌（荣和），必须至少拥有 1 颗豆（通行证）或构成大牌（大对子、七对、龙七对、清一色、单钓、抢杠胡）；而自摸胡牌不受豆数限制，无豆也可自摸平胡！
# 冲锋鸡与责任鸡
- 冲锋鸡：全场第一张被打出的幺鸡（1s）若未被其他玩家碰或杠走，打出者即为【冲锋鸡】，结算时额外获得 +2 鸡分加成（金鸡时翻倍为 +4）。
- 责任鸡：若全场第一张被打出的幺鸡（1s）被其他玩家碰或明杠，则变为【责任鸡】，打出者立即向碰/杠者赔付 2 分！
# 翻鸡与金鸡
- 有人胡牌结束本局时，从牌墙翻出 1 张鸡牌指示牌（chickenIndicator），同花色循环顺位的下一张（1→2→…→9→1）即为本局【翻鸡（luckyChicken）】。
- 若翻出九条（9s），顺位下一张恰好为幺鸡（1s），则形成【金鸡】，所有幺鸡分值翻倍！
- 所有胡牌及听牌玩家手牌、副露、弃牌河中的每一张幺鸡（1s）与翻鸡均计入鸡分奖励。
''';

const _harbinRules = '''
# 哈尔滨麻将（开门报听 · 暗宝牌 · 红中满天飞 · 刮大风）
4 人对局，使用万、筒、条（108 张）外加 4 张红中（7z），共 112 张牌。
# 开门与报听（上听）
- 玩家可通过吃（仅上家）、碰、杠操作开门（kaimen），并在手牌距离胡牌仅差 1 张（听牌）时声明【报听（上听）】并打出一张牌。
- 报听后手牌锁定听口，且只有已报听的玩家才能在牌桌视图中看到本局暗藏的【宝牌（baoTile）】！
# 摸宝、红中满天飞与刮大风
- 摸宝胡牌：每局发牌后从牌墙尾部抽出 1 张秘密宝牌（对未报听者隐藏）。已报听玩家轮到自己摸牌时，若自摸摸到【宝牌】，无论是否属于原本所听的牌，均可立即声明【摸宝】直接胡牌，番数翻倍！
- 红中满天飞：已报听玩家自摸摸到【红中（7z）】时，同样可立即按【摸宝 / 红中满天飞】直接胡牌并翻倍结算！
- 刮大风：已报听玩家自摸摸到与自己手牌暗刻或已碰副露相同的第 4 张牌时，立即触发【刮大风】获得全场额外赏分加成，也可直接凭刮大风翻倍胡牌！
''';

